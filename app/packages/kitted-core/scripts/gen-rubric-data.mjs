// Regenerates src/rubricData.ts from handoff/fixtures/rubric.json (the bundled rubric tables + fix catalog), and
// src/partsData.ts from handoff/fixtures/parts.json (the parts engine's tables and numbers, versioned on its own).
// Run after make_rubric_json.py / make_parts_json.py:   node scripts/gen-rubric-data.mjs
// Plain Node, no dependencies. The output is a TS const so the same data works in React Native (Metro),
// a Cloudflare Worker and Vitest without JSON-import configuration.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
// handoff/fixtures/rubric.json, from handoff/ts/kitted-core or app/packages/kitted-core.
const src = [resolve(here, "../../../fixtures/rubric.json"), resolve(here, "../../../../handoff/fixtures/rubric.json")].find((p) => existsSync(p));
if (!src) throw new Error("handoff/fixtures/rubric.json not found");
const out = resolve(here, "../src/rubricData.ts");
const data = JSON.parse(readFileSync(src, "utf8"));

const body =
  "// GENERATED by scripts/gen-rubric-data.mjs from handoff/fixtures/rubric.json. Do not edit by hand:\n" +
  "// change rubric.py / make_rubric_json.py, regenerate rubric.json, then re-run the script.\n" +
  'import type { RubricData } from "./types";\n\n' +
  "export const RUBRIC_DATA: RubricData = " +
  JSON.stringify(data, null, 1) +
  ";\n";
writeFileSync(out, body);
console.log(`wrote ${out} (rubric ${data.version}, engine ${data.engine}, sha ${data.rubricSha256.slice(0, 12)})`);

// The parts engine (parts.json, from make_parts_json.py).
const partsSrc = resolve(dirname(src), "parts.json");
if (existsSync(partsSrc)) {
  const parts = JSON.parse(readFileSync(partsSrc, "utf8"));
  const partsOut = resolve(here, "../src/partsData.ts");
  writeFileSync(
    partsOut,
    "// GENERATED by scripts/gen-rubric-data.mjs from handoff/fixtures/parts.json. Do not edit by hand:\n" +
      "// change parts_proto.py / make_parts_json.py, regenerate parts.json, then re-run the script.\n" +
      'import type { PartsData } from "./parts";\n\n' +
      "export const PARTS_DATA: PartsData = " +
      JSON.stringify(parts, null, 1) +
      ";\n",
  );
  console.log(`wrote ${partsOut} (parts ${parts.version}, ${parts.label}, sha ${parts.sourceSha256.slice(0, 12)})`);
}

// The parts engine's fix catalog (handoff/fixtures/fixes.json -> "parts"; reference parts_fixes.py, #208).
const fixesSrc = resolve(dirname(src), "fixes.json");
if (existsSync(fixesSrc)) {
  const catalog = JSON.parse(readFileSync(fixesSrc, "utf8")).parts;
  if (catalog) {
    const fixesOut = resolve(here, "../src/partsFixesData.ts");
    writeFileSync(
      fixesOut,
      "// GENERATED by scripts/gen-rubric-data.mjs from handoff/fixtures/fixes.json (\"parts\"). Do not edit by hand:\n" +
        "// change fixes.json (and parts_fixes.py if the logic changes), then re-run the script.\n" +
        'import type { PartsFixCatalog } from "./partsFixes";\n\n' +
        "export const PARTS_FIXES_DATA: PartsFixCatalog = " +
        JSON.stringify(catalog, null, 1) +
        ";\n",
    );
    console.log(`wrote ${fixesOut} (parts fix catalog ${catalog.version}, ${catalog.candidates.length} candidates)`);
  }
}
