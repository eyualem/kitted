// T61 · NR1.7 and NR8.1 (core side): the parity fixtures hold the NR1/NR2 cases, generated from Python
// (handoff/fixtures/make_parts_parity.py and make_parity.py), and core matches Python on every one of them.
// Never hand-edit a fixture: until the generators add the cases and the fixtures are regenerated, this file is red.
// No network, $0.
import { describe, expect, it } from "vitest";
import { score, type Reading, type Styles } from "../src/index";
import { diff, loadJSON, toPy } from "./helpers";
import { v15Engine } from "./t69";

interface PCase { src: string; reading: string; occasion: string; styles: [string, number][]; boldness: string; second_look: any; tune?: string; expected: Record<string, any> }
interface RCase { reading: string; occasion: string; styles: [string, number][]; boldness: string; expected: Record<string, any> }
const P = loadJSON<{ readings: Record<string, Reading>; cases: PCase[] }>("parts_parity.json");
const RP = loadJSON<{ readings: Record<string, Reading>; cases: RCase[] }>("rubric_parity.json");
const readingOf = (id: string): Reading => (P.readings[id] ?? RP.readings[id])!;

// The case names the generator (make_parts_parity.py) must add, as "parts-edge:<name>", with Python's exact answer.
const NAMED: Record<string, { reason?: string; slot?: string; notRated?: string[] }> = {
  nr_dress: { reason: "womenswear" }, nr_skirt: { reason: "womenswear" },
  nr_traditional: { reason: "traditional" }, nr_costume: { reason: "costume_or_uniform" },
  nr_unsure_top: { reason: "unreadable", slot: "top" }, nr_unsure_jacket: { reason: "unreadable", slot: "jacket" },
  nr_unsure_pants: { reason: "unreadable", slot: "pants" },
  nr_order_costume_skirt: { reason: "costume_or_uniform" }, nr_order_traditional_dress: { reason: "traditional" },
  nr_order_dress_unsure_jacket: { reason: "womenswear" }, nr_dress_unsure: { reason: "womenswear" },
  nr_heels: { notRated: ["shoes not rated"] }, nr_traditional_shoe_footwear: { notRated: ["shoes not rated"] },
  nr_traditional_shoe_category: { notRated: ["shoes not rated"] },
  nr_unsure_shoes: {}, nr_toponly_unsure_pants: { notRated: ["bottom half"] }, nr_unsure_watch: {},
};
const NEW_REASONS = ["costume_or_uniform", "traditional", "womenswear", "unreadable"];
const V15 = v15Engine();

describe("NR1.7 · the NR1/NR2 cases are parity fixtures, and core matches Python", () => {
  for (const [name, want] of Object.entries(NAMED)) {
    it(`NR1.7 · parts parity has "parts-edge:${name}" with Python's answer, and scoreParts equals it`, () => {
      const cs = P.cases.filter((c) => c.src === `parts-edge:${name}` && !c.tune);
      expect(cs.length).toBeGreaterThan(0);
      for (const c of cs) {
        const e = c.expected;
        expect(e["reason"] ?? null).toBe(want.reason ?? null);
        expect(e["unreadable_slot"] ?? null).toBe(want.slot ?? null);
        if (want.reason) expect(e["overall"]).toBeNull();
        else expect(typeof e["overall"]).toBe("number");
        if (want.notRated) expect(e["not_rated"]).toEqual(want.notRated);
        const got = V15.scoreParts(readingOf(c.reading), { occasion: c.occasion, styles: c.styles as Styles, boldness: c.boldness, secondLook: c.second_look }) as any;
        expect(got.overall).toBe(e["overall"]);
        expect(got.reason ?? null).toBe(e["reason"] ?? null);
        expect(got.unreadableSlot ?? null).toBe(e["unreadable_slot"] ?? null);
        if (want.notRated) expect(got.notRated).toEqual(e["not_rated"]);
      }
    });
  }

  it("NR1.7 · rubric parity holds a case for each new reason (and the slot), generated by rubric.py, and core matches", () => {
    for (const reason of NEW_REASONS) {
      const cs = RP.cases.filter((c) => c.expected["reason"] === reason);
      expect([reason, cs.length > 0]).toEqual([reason, true]);
      for (const c of cs) {
        expect(c.expected["overall"]).toBeNull();
        expect(diff(`${c.reading}`, toPy(score(RP.readings[c.reading]!, { occasion: c.occasion, styles: c.styles as Styles, boldness: c.boldness })), c.expected)).toEqual([]);
      }
    }
    const slots = new Set(RP.cases.filter((c) => c.expected["reason"] === "unreadable").map((c) => c.expected["unreadable_slot"]));
    expect(slots).toEqual(new Set(["top", "jacket", "pants"]));
    expect(RP.cases.some((c) => c.expected["not_rated"]?.includes("shoes not rated"))).toBe(true);
  });
});

describe("NR8.1 · only the readings with a trigger changed", () => {
  // An independent oracle of the spec's rules; it must agree with what Python wrote into every fixture case.
  function predicted(r: Reading): string | null | "skip" {
    const scene: any = r.scene ?? {};
    if (scene.clothed !== "fully") return "skip";
    const upper = scene.framing === "upper_only";
    let gs: any[] = r.garments.filter((g: any) => g.category !== "accessory");
    const hasBottomPieces = gs.some((g) => g.category === "bottom" || g.category === "footwear");
    if (upper && gs.some((g) => g.subcategory === "dress" || g.subcategory === "skirt") && hasBottomPieces) return "skip";
    if (!gs.some((g) => g.certainty !== "unsure")) return "skip"; // the old nothing_readable path: order not settled by the spec
    if (scene.costume_or_uniform === true) return "costume_or_uniform";
    if (gs.some((g) => g.category === "traditional" && g.subcategory !== "traditional_shoe")) return "traditional";
    if (gs.some((g) => g.subcategory === "dress" || g.subcategory === "skirt")) return "womenswear";
    if (scene.shoes_visible === false) gs = gs.filter((g) => g.category !== "footwear");
    if (upper) gs = gs.filter((g) => g.category !== "bottom" && g.category !== "footwear");
    const u = gs.find((g) => g.certainty === "unsure" && ["top", "outerwear", "bottom"].includes(g.category));
    return u ? "unreadable" : null;
  }
  it("NR8.1 · in every parts-parity case, the result is blocked exactly when a trigger is in the reading, with the oracle's reason", () => {
    const bad: string[] = [];
    let checked = 0;
    for (const c of P.cases) {
      if ("error" in c.expected || c.expected["overall"] === undefined) continue;
      const want = predicted(readingOf(c.reading));
      if (want === "skip") continue;
      checked++;
      const got = NEW_REASONS.includes(c.expected["reason"]) ? c.expected["reason"] : null;
      if (got !== want) bad.push(`${c.src} ${c.reading}: fixture ${got}, oracle ${want}`);
      if (bad.length > 15) break;
    }
    expect(bad).toEqual([]);
    expect(checked).toBeGreaterThan(30000);
  });
  it("NR8.1 · the same on every rubric-parity case", () => {
    const bad: string[] = [];
    for (const c of RP.cases) {
      const want = predicted(RP.readings[c.reading]!);
      if (want === "skip") continue;
      const got = NEW_REASONS.includes(c.expected["reason"]) ? c.expected["reason"] : null;
      if (got !== want) bad.push(`${c.reading}: fixture ${got}, oracle ${want}`);
      if (bad.length > 15) break;
    }
    expect(bad).toEqual([]);
  });
  it("NR8.1 · no case in either fixture keeps the old traditional token", () => {
    expect(RP.cases.filter((c) => (c.expected["not_rated"] ?? []).includes("traditional garment (not rated)")).length).toBe(0);
    expect(P.cases.filter((c) => (c.expected["not_rated"] ?? []).includes("traditional garment (not rated)")).length).toBe(0);
  });
});
