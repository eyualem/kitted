// Generates src/features/ask/guide.generated.ts from rubric/stylist-guide.md (the stylist chat's context, 07 §7.1).
// Run from app/: `node scripts/gen-guide.mjs`. Don't hand-edit the output; change the guide and re-run
// (askGemini.test.ts fails when they differ).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = join(dirname(fileURLToPath(import.meta.url)), '..');
const md = readFileSync(join(APP, '../rubric/stylist-guide.md'), 'utf8');
const out = `// Generated by scripts/gen-guide.mjs from rubric/stylist-guide.md. Don't edit; change the guide and re-run.\nexport const STYLIST_GUIDE: string = ${JSON.stringify(md)};\n`;
writeFileSync(join(APP, 'src/features/ask/guide.generated.ts'), out);
console.log(`guide.generated.ts: ${md.length} chars`);
