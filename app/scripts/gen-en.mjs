// Generates src/i18n/en.generated.ts from the copy deck in handoff/02-screens.md §5.
// Run from app/: `node scripts/gen-en.mjs`. Don't hand-edit the output; change 02 and re-run.
// Range rows ("`a.x` … `a.y` | A · B · …") are expanded with RANGES below.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP = join(dirname(fileURLToPath(import.meta.url)), '..');
const SPEC = join(APP, '../handoff/02-screens.md');
const OUT = join(APP, 'src/i18n/en.generated.ts');

const RANGES = {
  'value.leg.skinny': ['value.leg.skinny', 'value.leg.slim', 'value.leg.straight', 'value.leg.relaxed', 'value.leg.wide'],
  'starter.item.1': Array.from({ length: 12 }, (_, i) => `starter.item.${i + 1}`),
};

const md = readFileSync(SPEC, 'utf8');
const start = md.indexOf('## 5. Copy deck');
const end = md.indexOf('\n## 6', start);
if (start < 0) throw new Error('Copy deck not found in 02-screens.md');
const deck = md.slice(start, end < 0 ? undefined : end);

const entries = [];
for (const line of deck.split('\n')) {
  if (!line.startsWith('| `')) continue;
  const cells = line.trim().split(/(?<!\\)\|/).slice(1, -1).map((c) => c.trim());
  if (cells.length < 3) throw new Error(`Bad row: ${line}`);
  const keyCell = cells[0];
  const value = cells[1].replace(/\\n/g, '\n');
  const firstKey = keyCell.match(/`([^`]+)`/)?.[1];
  if (!firstKey) throw new Error(`No key: ${line}`);
  if (keyCell.includes('…')) {
    const keys = RANGES[firstKey];
    if (!keys) throw new Error(`Unknown range row starting at ${firstKey}`);
    const values = value.split(' · ');
    if (values.length !== keys.length) throw new Error(`Range ${firstKey}: ${values.length} values for ${keys.length} keys`);
    keys.forEach((k, i) => entries.push([k, values[i]]));
  } else {
    entries.push([firstKey, value]);
  }
}

const seen = new Set();
for (const [k] of entries) {
  if (seen.has(k)) throw new Error(`Duplicate key ${k}`);
  seen.add(k);
}

const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-en.mjs from handoff/02-screens.md §5 (the copy deck). Don't edit.\n` +
    `// ${entries.length} strings.\n\n` +
    `export const enGenerated = {\n${body}\n} as const;\n`,
);
console.log(`wrote ${entries.length} strings to ${OUT}`);
